void write32(void *addr, uint32_t val) {
    asm volatile (
        "dmb sy\n\t"
        "str %w[val], [%[addr]]\n\t"
        "dmb sy\n\t"
        :
        : [val] "r" (val), [addr] "r" (addr)
        : "memory"
    );
}

uint32_t read32(void *addr) {
    uint32_t val;
    asm volatile (
        "dmb sy\n\t"
        "ldr %w[val], [%[addr]]\n\t"
        "dmb sy\n\t"
        : [val] "=r" (val)
        : [addr] "r" (addr)
        : "memory"
    );
    return val;
}

