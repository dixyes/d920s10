int reinstall_ssdt (EFI_ACPI_TABLE_PROTOCOL *acpi_table, EFI_ACPI_SDT_PROTOCOL *acpi_sdt) {
    efi_status_t ret;
    EFI_ACPI_SDT_HEADER *pTable = NULL;
    EFI_ACPI_TABLE_VERSION dummy;
    uintn_t key;
    char sign[5] = { 0 };
    for (int i = 0; i < 256; i++) {
        ret = acpi_sdt->GetAcpiTable(i, &pTable, &dummy, &key);
        if (EFI_SUCCESS != ret) {
            printf("not found %d\n", i);
            break;
        }
        memcpy(sign, &pTable->Signature, 4);
        printf("found \"%s\" at %d\n", sign, i);

        if (pTable->Signature == 0x54445353 /* SSDT */) {
            printf("uninstall SSDT at %d\n", i);

            // pTable->Signature = 0x584d454f;
            
            ret = acpi_table->UninstallAcpiTable(acpi_table, key);
            if (EFI_SUCCESS != ret) {
                printf("failed UninstallAcpiTable SSDT\n");
                return 1;
            }
            break;
        }
    }

    return install_table(acpi_table, (const char *)sr358fv2_nofuck2_aml, sr358fv2_nofuck2_aml_len);
}

