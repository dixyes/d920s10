char *dmi_string(const EFI_SMBIOS_TABLE_HEADER *dm, uint8_t s)
{
	char *bp = (char *)dm;

	if (!s || !bp)
		return NULL;

	bp += dm->Length;
	while (s > 1 && *bp) {
		bp += strlen(bp);
		bp++;
		s--;
	}

	return !*bp ? NULL : bp;
}

